"""Writes stock_hashes.h: FNV-1a 64 hashes of the example mods shipped by older versions.
The installer replaces an existing mod file only if it is one of these (= not changed by the user)."""
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(ROOT, '..', '..', 'build')
OLD = ['gdpy-0.1/files/gdpy/mods', 'PyModder-0.2/files/pymodder/mods', 'PyModder-0.3/files/pymodder/mods',
       'PyModder-0.4/files/pymodder/mods', 'PyModder-0.5/files/pymodder/mods',
       'PyModder-0.6/files/pymodder/mods']
SHA_LIST = os.path.join(ROOT, '..', '..', 'pkg', 'stock_mods.txt')


def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


import hashlib
import re
hashes = {}
sha = set()
# keep what the existing files already list (old builds may be gone from build/)
hdr = os.path.join(ROOT, 'stock_hashes.h')
if os.path.isfile(hdr):
    for m in re.finditer(r'0x([0-9a-f]{16})ULL,\s*//\s*(\S+)', open(hdr).read()):
        hashes[int(m.group(1), 16)] = m.group(2)
if os.path.isfile(SHA_LIST):
    sha.update(l.strip() for l in open(SHA_LIST) if len(l.strip()) == 64)
for rel in OLD:
    base = os.path.join(BUILD, rel)
    if not os.path.isdir(base):
        continue
    for dp, dn, fn in os.walk(base):
        dn[:] = [d for d in dn if d not in ('__pycache__', 'data')]
        for f in fn:
            p = os.path.join(dp, f)
            data = open(p, 'rb').read()
            hashes[fnv(data)] = os.path.relpath(p, BUILD)
            sha.add(hashlib.sha256(data).hexdigest())
with open(os.path.join(ROOT, 'stock_hashes.h'), 'w') as out:
    out.write('// generated by gen_stock.py: example mods from older PyModder versions\n')
    out.write('static const unsigned long long STOCK_HASHES[] = {\n')
    for h, name in sorted(hashes.items(), key=lambda x: x[1]):
        out.write('    0x%016xULL,  // %s\n' % (h, name.replace('\\', '/')))
    out.write('};\n')
print(len(hashes), 'hashes')
if len(sys.argv) > 1:   # SHA-256 list for install.ps1
    with open(sys.argv[1], 'w') as out:
        out.write('\n'.join(sorted(sha)) + '\n')
