"""Generates proxy export stubs for the PyModder loader (one DLL per proxied system DLL).

Each export is a tiny asm stub `jmp *pm_fwd[i]`. Slots start at a lazy resolver that loads the real
DLL from System32 on the first call (no LoadLibrary inside DllMain), so any signature works.
"""
import os
import sys

MINGW = '/data/zig/lib/libc/mingw/lib-common'
HERE = os.path.dirname(os.path.abspath(__file__))

XINPUT = [('XInputGetState', 2), ('XInputSetState', 3), ('XInputGetCapabilities', 4), ('XInputEnable', 5),
          ('XInputGetAudioDeviceIds', 6), ('XInputGetBatteryInformation', 7), ('XInputGetKeystroke', 8),
          (None, 100), (None, 101), (None, 102), (None, 103), (None, 104), (None, 108)]


def from_def(name):
    out = []
    for ln in open(os.path.join(MINGW, name)):
        ln = ln.split(';')[0].strip()
        if not ln or ln.startswith(('LIBRARY', 'EXPORTS')):
            continue
        sym = ln.split()[0].split('@')[0]
        out.append((sym, None))
    return out


VARIANTS = {
    'XInput1_4': (XINPUT, 1167),          # ERROR_DEVICE_NOT_CONNECTED if the real one is missing
    'opengl32': (from_def('opengl32.def'), 0),
    'version': (from_def('version.def'), 0),
}


def gen(dll, exports, missing_ret):
    n = len(exports)
    inc = ['// generated by gen_proxy.py - proxy for %s.dll' % dll,
           '#define PROXY_DLL L"%s.dll"' % dll,
           '#define PROXY_COUNT %d' % n,
           '#define PROXY_MISSING_RET %d' % missing_ret,
           'static const char* const pm_names[PROXY_COUNT] = {']
    inc += ['    %s,' % ('"%s"' % nm if nm else '(const char*)(uintptr_t)%d' % o) for nm, o in exports]
    inc.append('};')
    asm = ['__asm__(".text\\n"']
    for i in range(n):
        asm.append('    ".globl pm_stub_%d\\n"' % i)
        asm.append('    "pm_stub_%d: jmpq *pm_fwd+%d(%%rip)\\n"' % (i, i * 8))
        asm.append('    "pm_lazy_%d: movl $%d, %%r10d\\n jmp pm_lazy_common\\n"' % (i, i))
    asm.append('    ".data\\n.globl pm_fwd\\n.p2align 3\\npm_fwd:\\n"')
    for i in range(n):
        asm.append('    ".quad pm_lazy_%d\\n"' % i)
    asm.append('    ".text\\n");')
    inc += asm
    d = ['LIBRARY %s' % dll, 'EXPORTS']
    for i, (nm, o) in enumerate(exports):
        if nm:
            d.append('    %s = pm_stub_%d%s' % (nm, i, ' @%d' % o if o else ''))
        else:
            d.append('    pm_ord%d = pm_stub_%d @%d NONAME' % (o, i, o))
    for e in ('pymodder_hook', 'pymodder_unhook', 'pymodder_status', 'pymodder_dir', 'pymodder_version',
              'pymodder_loader'):
        d.append('    ' + e)
    open(os.path.join(HERE, 'proxy', dll + '.inc'), 'w').write('\n'.join(inc) + '\n')
    open(os.path.join(HERE, 'proxy', dll + '.def'), 'w').write('\n'.join(d) + '\n')
    print(dll, n, 'exports')


if __name__ == '__main__':
    for k, (ex, mr) in VARIANTS.items():
        gen(k, ex, mr)
